#include "ft.h"

int		ft_strcmp(char *s1, char *s2)
{
	int i;

	i = 0;
	if (*s1 == '\0' && *s2 == '\0')
		return (0);
	while ((s1[i] && s2[i]) && s1[i] == s2[i])
		i++;
	return ((unsigned int)s1[i] - (unsigned int)s2[i]);
}
